GLYPHS = {ch: [int(b, 16) for b in cols.split()] for ch, cols in _RAW.items()}


def render_columns(text: str, gap: int = 1) -> list:
    """Text -> list of column bitmasks (7 rows each)."""
    cols = []
    for ch in text.upper():
        glyph = GLYPHS.get(ch, GLYPHS["?"])
        cols.extend(glyph)
        cols.extend([0] * gap)
    return cols
